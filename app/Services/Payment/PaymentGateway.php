<?php

namespace App\Services\Payment;

use App\Models\Billing\Payment;
use Illuminate\Http\Request;

/**
 * Единый интерфейс платёжного провайдера.
 *
 * Смысл в том, чтобы весь остальной код (контроллеры, подписки, доступ)
 * ничего не знал о конкретном банке. Подключение Алифа/DC Pay сводится
 * к новому классу с этими тремя методами и строчке в config/payment.php.
 *
 * ВАЖНО: реквизиты карты никогда не проходят через наш сервер —
 * createCheckout возвращает ссылку на страницу оплаты провайдера,
 * куда мы отправляем пользователя.
 */
interface PaymentGateway
{
    /**
     * Создаёт платёж на стороне провайдера и возвращает URL,
     * на который нужно отправить пользователя для ввода карты.
     */
    public function createCheckout(Payment $payment): string;

    /**
     * Разбирает вебхук провайдера. Возвращает null, если запрос
     * не удалось сопоставить с платежом или подпись неверна.
     *
     * Реализация ОБЯЗАНА проверять подпись запроса — без этого любой
     * желающий сможет подделать «оплату» и получить доступ бесплатно.
     */
    public function parseWebhook(Request $request): ?WebhookResult;

    /** Машинное имя провайдера, попадает в payments.provider. */
    public function name(): string;
}
